"""概念板块排除规则（共享口径）

券商荐股页（broker_recommend）与基金扎堆页（fund_crowd）的概念榜共用同一排除口径，
确保两个页面的概念板块分布数据一致。

排除两类宽泛、非主题的干扰概念：
1. 交易机制类：融资融券/沪股通/深股通（覆盖面过广、信号弱）
2. 指数成分类：沪深300/中证500 等（偏市场代表性、非主题，会霸榜干扰）

指数成分概念在数据源里存在多种命名变体（如"沪深300""沪深300样本股"
"中证500成份股"），无法用精确匹配覆盖，故采用关键词子串模糊匹配：
概念名包含任一关键词即排除。
"""

# 排除关键词（子串模糊匹配，概念名包含任一即排除）
EXCLUDED_CONCEPT_KEYWORDS: tuple[str, ...] = (
    # 交易机制类
    "融资融券",
    "沪股通",
    "深股通",
    # 指数成分类（关键词匹配，覆盖"沪深300""沪深300样本股""中证500成份股"等变体）
    "沪深300",
    "中证500",
    "中证1000",
    "中证800",
    "上证50",
    "创业板指",
    "MSCI中国",
    "富时罗素",
    "标普道琼斯A股",
    # 指数成分后缀（"XX样本股""XX成份股"这类指数成分概念，非主题，一并排除）
    "样本股",
    "成份股",
    "成分股",
)


def is_excluded_concept(name: str | None) -> bool:
    """判断概念名是否应被排除（子串模糊匹配）。

    Args:
        name: 概文名称，None 或空串视为不排除（由调用方另行处理空值）

    Returns:
        True 表示该概念应排除
    """
    if not name:
        return False
    return any(kw in name for kw in EXCLUDED_CONCEPT_KEYWORDS)

